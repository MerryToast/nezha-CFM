function buildLatencyWindow(baseCt: number, baseCu: number, baseCm: number, baseBd: number) {
  const ping = []
  const loss = []
  for (let i = 19; i >= 0; i--) {
    const ts = now - i * 6 * 60 * 1000
    const jitter = (idx: number) => Math.round((Math.sin(i * 0.9 + idx) + 1) * 8)
    const isCmTimeout = i === 4
    ping.push({
      ts,
      ct: baseCt + jitter(1),
      cu: baseCu + jitter(2),
      cm: isCmTimeout ? null : baseCm + jitter(3),
      bd: baseBd === -1 ? (false as const) : baseBd + jitter(4),
    })
    loss.push({
      ts,
      ct: 0,
      cu: i === 7 ? 2.5 : 0,
      cm: isCmTimeout ? 100 : 0,
      bd: baseBd === -1 ? (false as const) : 0,
    })
  }
  return { ping, loss }
}

